#!/usr/bin/env node

const fs = require('fs');
const os = require('os');
const path = require('path');

const SOURCE_PATH = path.join('design-system', 'source', 'novel-design.tokens.json');

const ensureDir = (dirPath) => {
  fs.mkdirSync(dirPath, { recursive: true });
};

const writeText = (absolutePath, content) => {
  ensureDir(path.dirname(absolutePath));
  fs.writeFileSync(absolutePath, content, 'utf8');
};

const writeJson = (absolutePath, data) => {
  writeText(absolutePath, `${JSON.stringify(data, null, 2)}\n`);
};

const resolveOutputRoot = (repoRoot, outputRoot) =>
  path.isAbsolute(outputRoot) ? outputRoot : path.join(repoRoot, outputRoot);

const loadSourceTokens = ({ repoRoot = path.resolve(__dirname, '..') } = {}) =>
  JSON.parse(fs.readFileSync(path.join(repoRoot, SOURCE_PATH), 'utf8'));

const flattenColorTokens = (tokens, mode) => {
  const flat = [];
  Object.entries(tokens.color).forEach(([group, values]) => {
    Object.entries(values).forEach(([name, pair]) => {
      flat.push({
        key: `color.${group}.${name}.${mode}`,
        value: pair[mode],
      });
    });
  });
  return flat;
};

const renderStyleDictionaryJson = (tokens) => {
  const dictionary = {
    color: tokens.color,
    space: Object.fromEntries(
      Object.entries(tokens.space).map(([key, value]) => [key, { value }]),
    ),
    radius: Object.fromEntries(
      Object.entries(tokens.radius).map(([key, value]) => [key, { value }]),
    ),
    motion: tokens.motion,
    typography: tokens.typography,
  };

  return dictionary;
};

const renderLess = (tokens) => {
  const lines = ['// Generated by scripts/novel-design-token-build.js'];

  ['light', 'dark'].forEach((mode) => {
    flattenColorTokens(tokens, mode).forEach(({ key, value }) => {
      lines.push(`@novel-design-${key.replace(/\./g, '-')}: ${value};`);
    });
  });

  Object.entries(tokens.space).forEach(([key, value]) => {
    lines.push(`@novel-design-space-${key}: ${value}px;`);
  });
  Object.entries(tokens.radius).forEach(([key, value]) => {
    lines.push(`@novel-design-radius-${key}: ${value}px;`);
  });
  Object.entries(tokens.motion.duration).forEach(([key, value]) => {
    lines.push(`@novel-design-motion-duration-${key}: ${value}ms;`);
  });

  return `${lines.join('\n')}\n`;
};

const toTypeScriptLiteral = (value, indentLevel = 0) => {
  const indent = '  '.repeat(indentLevel);
  const nextIndent = '  '.repeat(indentLevel + 1);

  if (Array.isArray(value)) {
    const rendered = value.map((item) => toTypeScriptLiteral(item, indentLevel + 1));
    return `[\n${rendered.map((item) => `${nextIndent}${item}`).join(',\n')}\n${indent}]`;
  }

  if (value && typeof value === 'object') {
    const renderedEntries = Object.entries(value).map(([key, itemValue]) => {
      const renderedKey = /^[A-Za-z_][A-Za-z0-9_]*$/.test(key)
        ? key
        : `"${key}"`;
      return `${nextIndent}${renderedKey}: ${toTypeScriptLiteral(itemValue, indentLevel + 1)}`;
    });
    return `{\n${renderedEntries.join(',\n')}\n${indent}}`;
  }

  return JSON.stringify(value);
};

const renderReactNative = (tokens) => {
  const lightColors = {};
  const darkColors = {};

  Object.entries(tokens.color).forEach(([group, values]) => {
    lightColors[group] = {};
    darkColors[group] = {};
    Object.entries(values).forEach(([name, pair]) => {
      lightColors[group][name] = pair.light;
      darkColors[group][name] = pair.dark;
    });
  });

  return `export const novelDesignLightTheme = ${toTypeScriptLiteral({
    color: lightColors,
    space: tokens.space,
    radius: tokens.radius,
    elevation: tokens.elevation,
    motion: tokens.motion,
    typography: tokens.typography,
  })} as const;\n\nexport const novelDesignDarkTheme = ${toTypeScriptLiteral({
    color: darkColors,
    space: tokens.space,
    radius: tokens.radius,
    elevation: tokens.elevation,
    motion: tokens.motion,
    typography: tokens.typography,
  })} as const;\n`;
};

const xmlName = (value) => value.replace(/\./g, '_').replace(/-/g, '_');

const renderAndroidXml = (tokens) => {
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>'];

  ['light', 'dark'].forEach((mode) => {
    flattenColorTokens(tokens, mode).forEach(({ key, value }) => {
      lines.push(`  <color name="novel_design_${xmlName(key)}">${value}</color>`);
    });
  });

  Object.entries(tokens.space).forEach(([key, value]) => {
    lines.push(`  <dimen name="novel_design_space_${key}">${value}dp</dimen>`);
  });
  Object.entries(tokens.radius).forEach(([key, value]) => {
    lines.push(`  <dimen name="novel_design_radius_${key}">${value}dp</dimen>`);
  });

  lines.push('</resources>');
  return `${lines.join('\n')}\n`;
};

const renderAndroidCompose = (tokens) => {
  const lightColors = flattenColorTokens(tokens, 'light')
    .map(({ key, value }) => `        "${key}" to Color(0xFF${value.slice(1)})`)
    .join(',\n');
  const darkColors = flattenColorTokens(tokens, 'dark')
    .map(({ key, value }) => `        "${key}" to Color(0xFF${value.slice(1)})`)
    .join(',\n');
  const space = Object.entries(tokens.space)
    .map(([key, value]) => `        "${key}" to ${value}.dp`)
    .join(',\n');

  return `package com.novel.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

object NovelDesignTokens {
    val LightColors = mapOf(
${lightColors}
    )

    val DarkColors = mapOf(
${darkColors}
    )

    val Space = mapOf(
${space}
    )
}
`;
};

const generateTokenArtifacts = ({
  repoRoot = path.resolve(__dirname, '..'),
  outputRoot = repoRoot,
} = {}) => {
  const tokens = loadSourceTokens({ repoRoot });
  const resolvedRoot = resolveOutputRoot(repoRoot, outputRoot);
  const outputs = {
    styleDictionaryPath: path.join(resolvedRoot, 'design-system', 'generated', 'style-dictionary.tokens.json'),
    lessPath: path.join(resolvedRoot, 'design-system', 'generated', 'tokens.less'),
    reactNativePath: path.join(resolvedRoot, 'src', 'design-system', 'tokens', 'novelDesignTokens.ts'),
    androidXmlPath: path.join(resolvedRoot, 'android', 'core-ui', 'src', 'main', 'res', 'values', 'novel_design_tokens.xml'),
    androidComposePath: path.join(resolvedRoot, 'android', 'core-ui', 'src', 'main', 'java', 'com', 'novel', 'ui', 'theme', 'NovelDesignTokens.kt'),
  };

  writeJson(outputs.styleDictionaryPath, renderStyleDictionaryJson(tokens));
  writeText(outputs.lessPath, renderLess(tokens));
  writeText(outputs.reactNativePath, renderReactNative(tokens));
  writeText(outputs.androidXmlPath, renderAndroidXml(tokens));
  writeText(outputs.androidComposePath, renderAndroidCompose(tokens));

  return outputs;
};

const checkTokenArtifacts = ({
  repoRoot = path.resolve(__dirname, '..'),
  outputRoot = repoRoot,
} = {}) => {
  const resolvedRoot = resolveOutputRoot(repoRoot, outputRoot);
  const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'novel-design-token-check-'));

  try {
    const fresh = generateTokenArtifacts({ repoRoot, outputRoot: tempDir });
    const expected = {
      styleDictionaryPath: path.join(resolvedRoot, 'design-system', 'generated', 'style-dictionary.tokens.json'),
      lessPath: path.join(resolvedRoot, 'design-system', 'generated', 'tokens.less'),
      reactNativePath: path.join(resolvedRoot, 'src', 'design-system', 'tokens', 'novelDesignTokens.ts'),
      androidXmlPath: path.join(resolvedRoot, 'android', 'core-ui', 'src', 'main', 'res', 'values', 'novel_design_tokens.xml'),
      androidComposePath: path.join(resolvedRoot, 'android', 'core-ui', 'src', 'main', 'java', 'com', 'novel', 'ui', 'theme', 'NovelDesignTokens.kt'),
    };

    const missing = Object.values(expected).filter((filePath) => !fs.existsSync(filePath));
    if (missing.length > 0) {
      return {
        ok: false,
        message: `Missing token artifact(s): ${missing.join(', ')}`,
      };
    }

    const mismatched = Object.keys(expected).filter((key) => {
      const currentContent = fs.readFileSync(expected[key], 'utf8');
      const freshContent = fs.readFileSync(fresh[key], 'utf8');
      return currentContent !== freshContent;
    });

    if (mismatched.length > 0) {
      return {
        ok: false,
        message: `Novel design token artifacts are stale: ${mismatched.join(', ')}`,
      };
    }

    return {
      ok: true,
      message: 'Novel design token artifacts are up to date.',
    };
  } finally {
    fs.rmSync(tempDir, { recursive: true, force: true });
  }
};

const main = () => {
  const command = process.argv[2] || 'generate';
  const repoRoot = path.resolve(__dirname, '..');

  if (command === 'generate') {
    const outputs = generateTokenArtifacts({ repoRoot });
    console.log(`Novel design token artifacts written to ${path.dirname(outputs.styleDictionaryPath)}`);
    return;
  }

  if (command === 'check') {
    const result = checkTokenArtifacts({ repoRoot });
    if (!result.ok) {
      console.error(result.message);
      process.exit(1);
    }
    console.log(result.message);
    return;
  }

  console.error(`Unknown command: ${command}`);
  process.exit(1);
};

module.exports = {
  checkTokenArtifacts,
  generateTokenArtifacts,
  loadSourceTokens,
};

if (require.main === module) {
  main();
}
